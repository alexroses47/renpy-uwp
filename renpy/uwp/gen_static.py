"""Turn Ren'Py's src/Setup into inputs for the static UWP build.

After `RENPY_STATIC=1 python setup.py generate` (Cython output in tmp/gen3-static, with PyInit_*
renamed to PyInit_<package>_<module>), this writes:
  - modules.cmake: RENPY_STATIC_SOURCES (absolute paths) for the selected modules
  - renpy_inittab.c: renpy_uwp_extend_inittab(), registering them as built-in modules
Same scheme as renpy-build tasks/librenpy.py and runtime/librenpy_inittab3.c.

Usage: python gen_static.py RENPY_ROOT OUT_DIR MODULE_PATTERN [MODULE_PATTERN...]
  patterns: exact names or prefixes ending in '.*' (e.g. renpy.pygame.*)
"""
import sys
from pathlib import Path


def selected(name, patterns):
    for p in patterns:
        if p.endswith(".*") and name.startswith(p[:-1]):
            return True
        if name == p:
            return True
    return False


def main():
    root, out = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
    patterns = sys.argv[3:]
    src = root / "src"
    modules, sources = [], []
    for line in (src / "Setup").read_text().splitlines():
        line = line.partition("#")[0].strip()
        if not line:
            continue
        name, *files = line.split()
        if not selected(name, patterns):
            continue
        modules.append(name)
        for f in files:
            f = f.replace("../tmp/gen/", "../tmp/gen3-static/")
            path = (src / f).resolve()
            if not path.exists():
                sys.exit(f"missing source for {name}: {path}")
            sources.append(path)
    missing = [p for p in patterns if not any(selected(m, [p]) for m in modules)]
    if missing:
        sys.exit(f"patterns matched no module: {missing}")

    out.mkdir(parents=True, exist_ok=True)
    uniq = list(dict.fromkeys(sources))
    (out / "modules.cmake").write_text(
        "set(RENPY_STATIC_SOURCES\n" + "".join(f'  "{p.as_posix()}"\n' for p in uniq) + ")\n")
    lines = ['/* Generated by renpy/uwp/gen_static.py. */', '#include "Python.h"', ""]
    for m in modules:
        lines.append(f"PyMODINIT_FUNC PyInit_{m.replace('.', '_')}(void);")
    lines += ["", "static struct _inittab renpy_uwp_inittab[] = {"]
    for m in modules:
        lines.append(f'    {{"{m}", PyInit_{m.replace(".", "_")}}},')
    lines += ["    {NULL, NULL},", "};", "",
              "/* Call before Py_PreInitialize/Py_InitializeFromConfig. Returns 0 on success. */",
              "int renpy_uwp_extend_inittab(void) { return PyImport_ExtendInittab(renpy_uwp_inittab); }", ""]
    (out / "renpy_inittab.c").write_text("\n".join(lines))
    print(f"{len(modules)} modules, {len(uniq)} sources -> {out}")
    for m in modules:
        print("  ", m)


if __name__ == "__main__":
    main()
